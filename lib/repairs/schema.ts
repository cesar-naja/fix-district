/**
 * Repair-request shape, limits, and validation. Pure code with no Firebase,
 * Clerk, or React imports, so the same rules run in the form (for hints) and
 * on the server (for enforcement). The server result is the only one trusted.
 */

export const DEVICE_TYPES = ["phone", "laptop", "tablet", "console"] as const;
export type DeviceType = (typeof DEVICE_TYPES)[number];

export const DEVICE_TYPE_LABEL: Record<DeviceType, string> = {
  phone: "Phone",
  laptop: "Laptop",
  tablet: "Tablet",
  console: "Console",
};

/** Only status that exists in this milestone. Assigned by the server. */
export type RepairStatus = "submitted";
export const INITIAL_STATUS: RepairStatus = "submitted";
export const STATUS_LABEL: Record<RepairStatus, string> = {
  submitted: "Submitted",
};

/** Upper bound on requests read per list. One extra is read to detect "more". */
export const LIST_LIMIT = 50;

export const LIMITS = {
  brand: { min: 1, max: 60 },
  model: { min: 1, max: 80 },
  description: { min: 10, max: 1000 },
} as const;

export type RepairInput = {
  deviceType: DeviceType;
  brand: string;
  model: string;
  description: string;
};

export type FieldName = keyof RepairInput;
export type FieldErrors = Partial<Record<FieldName, string>>;

/** What the form posts, as plain strings (also used to re-fill the form). */
export type RepairFormValues = Record<FieldName, string>;

export const EMPTY_VALUES: RepairFormValues = {
  deviceType: "",
  brand: "",
  model: "",
  description: "",
};

export type ValidationResult =
  | { ok: true; data: RepairInput }
  | { ok: false; errors: FieldErrors; values: RepairFormValues };

// Control characters other than tab and newline have no place in free text.
const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g;

function clean(value: unknown, multiline: boolean): string {
  if (typeof value !== "string") return "";
  let text = value.replace(/\r\n?/g, "\n").replace(CONTROL_CHARS, "");
  if (!multiline) text = text.replace(/\s+/g, " ");
  return text.trim();
}

function isDeviceType(value: string): value is DeviceType {
  return (DEVICE_TYPES as readonly string[]).includes(value);
}

function checkText(
  label: string,
  value: string,
  limit: { max: number },
): string | undefined {
  if (value.length === 0) return `Enter the ${label}.`;
  if (value.length > limit.max) {
    return `The ${label} must be ${limit.max} characters or fewer.`;
  }
  return undefined;
}

/**
 * Validates untrusted input. Only the four known fields are read, so any
 * extra properties a caller sends (owner, status, timestamps, ...) are
 * ignored here and can never reach storage.
 */
export function validateRepairInput(raw: {
  [K in FieldName]?: unknown;
}): ValidationResult {
  const values: RepairFormValues = {
    deviceType: clean(raw.deviceType, false),
    brand: clean(raw.brand, false),
    model: clean(raw.model, false),
    description: clean(raw.description, true),
  };
  const errors: FieldErrors = {};

  if (!isDeviceType(values.deviceType)) {
    errors.deviceType = "Choose the type of device.";
  }

  const brandError = checkText("brand", values.brand, LIMITS.brand);
  if (brandError) errors.brand = brandError;

  const modelError = checkText("model", values.model, LIMITS.model);
  if (modelError) errors.model = modelError;

  if (values.description.length === 0) {
    errors.description = "Describe the problem.";
  } else if (values.description.length < LIMITS.description.min) {
    errors.description = `Add a little more detail (at least ${LIMITS.description.min} characters).`;
  } else if (values.description.length > LIMITS.description.max) {
    errors.description = `The description must be ${LIMITS.description.max} characters or fewer.`;
  }

  if (Object.keys(errors).length > 0) return { ok: false, errors, values };

  return {
    ok: true,
    data: {
      deviceType: values.deviceType as DeviceType,
      brand: values.brand,
      model: values.model,
      description: values.description,
    },
  };
}

/** Per-form idempotency key: a random UUID generated by the server. */
const KEY_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isValidRequestKey(value: unknown): value is string {
  return typeof value === "string" && KEY_PATTERN.test(value);
}

/** Repair IDs are 40 lowercase hex characters (see repository.ts). */
const ID_PATTERN = /^[0-9a-f]{40}$/;

export function isValidRepairId(value: unknown): value is string {
  return typeof value === "string" && ID_PATTERN.test(value);
}
